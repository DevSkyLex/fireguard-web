import { Service } from '@angular/core';
import type { Observable } from 'rxjs';
import { HydraApiService } from '@core/api';
import type { ApiRequestOptions } from '@core/api/models';
import type {
  ConfirmTotpInput,
  ConfirmTotpOutput,
  DisableTotpInput,
  DisableTotpOutput,
  GenerateRecoveryCodesOutput,
  RecoveryCodesStatusOutput,
  SetupTotpOutput,
} from '@features/account/models';

/**
 * Service TotpService
 * @class TotpService
 *
 * @description
 * Account-owned API service for the authenticator app (TOTP) enrollment
 * lifecycle exposed by the `Otp` module: generating a pending secret
 * (`setup`), activating it with a verification code (`confirm`), and
 * disabling an active enrollment with a proof-of-possession code (`disable`).
 *
 * @version 2.0.0
 *
 * @author Valentin FORTIN <contact@valentin-fortin.pro>
 *
 * @extends {HydraApiService}
 */
@Service()
export class TotpService extends HydraApiService {
  /**
   * Property BASE_PATH
   * @readonly
   * @static
   *
   * @description
   * Base path for the TOTP resource exposed by the `Otp` module.
   *
   * @access private
   * @since 1.0.0
   *
   * @type {string}
   */
  private static readonly BASE_PATH: string = '/api/otp/totp';

  /**
   * Method setup
   *
   * @description
   * Requests a new TOTP secret and `otpauth://` provisioning URI for
   * authenticator app enrollment. Persists it server-side as a pending
   * enrollment; calling this again replaces the previous pending secret.
   *
   * @access public
   * @since 1.0.0
   *
   * @param {ApiRequestOptions} options - Transport identity retained for the same immutable write
   *   intent.
   *
   * @returns {Observable<SetupTotpOutput>} Observable emitting the generated secret and URI.
   */
  public setup(options?: ApiRequestOptions): Observable<SetupTotpOutput> {
    return this.postAction<SetupTotpOutput>(`${TotpService.BASE_PATH}/setup`, options);
  }

  /**
   * Method confirm
   *
   * @description
   * Verifies a code from the authenticator app against the pending secret
   * and, on success, activates TOTP for the authenticated user.
   *
   * @access public
   * @since 1.0.0
   *
   * @param {string} code - 6-digit code generated by the authenticator app.
   * @param {ApiRequestOptions} options - Transport identity retained for the same immutable write
   *   intent.
   *
   * @returns {Observable<ConfirmTotpOutput>} Observable emitting the activation result.
   */
  public confirm(code: string, options?: ApiRequestOptions): Observable<ConfirmTotpOutput> {
    return this.post<ConfirmTotpInput, ConfirmTotpOutput>(
      `${TotpService.BASE_PATH}/confirm`,
      { code },
      options,
    );
  }

  /**
   * Method disable
   *
   * @description
   * Disables TOTP for the authenticated user. Requires a valid current TOTP
   * code as proof of possession.
   *
   * @access public
   * @since 1.0.0
   *
   * @param {string} code - Current 6-digit code from the authenticator app.
   * @param {'totp' | 'recovery_code'} proofType - Selected proof type for disabling TOTP.
   * @param {ApiRequestOptions} options - Transport identity retained for the same immutable write
   *   intent.
   *
   * @returns {Observable<DisableTotpOutput>} Observable emitting the disable result.
   */
  public disable(
    code: string,
    proofType: 'totp' | 'recovery_code' = 'totp',
    options?: ApiRequestOptions,
  ): Observable<DisableTotpOutput> {
    return this.post<DisableTotpInput, DisableTotpOutput>(
      `${TotpService.BASE_PATH}/disable`,
      proofType === 'totp' ? { code } : { code, proofType },
      options,
    );
  }

  /**
   * Method recoveryStatus
   *
   * @description
   * Reads availability only; raw codes are never returned by this query.
   *
   * @access public
   * @since 1.0.0
   *
   * @returns {Observable<RecoveryCodesStatusOutput>} Result of the current operation.
   */
  public recoveryStatus(): Observable<RecoveryCodesStatusOutput> {
    return this.getOne<RecoveryCodesStatusOutput>(`${TotpService.BASE_PATH}/recovery-codes`);
  }

  /**
   * Method generateRecoveryCodes
   *
   * @description
   * Generates one new set after current TOTP proof, preserving the caller's retry identity.
   *
   * @access public
   * @since 1.0.0
   *
   * @param {string} code - Current code.
   * @param {ApiRequestOptions} options - Transport identity retained for the same immutable write
   *   intent.
   *
   * @returns {Observable<GenerateRecoveryCodesOutput>} Result of the current operation.
   */
  public generateRecoveryCodes(
    code: string,
    options?: ApiRequestOptions,
  ): Observable<GenerateRecoveryCodesOutput> {
    return this.post<{ code: string }, GenerateRecoveryCodesOutput>(
      `${TotpService.BASE_PATH}/recovery-codes`,
      { code },
      options,
    );
  }
}
