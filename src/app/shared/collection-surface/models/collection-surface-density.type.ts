/**
 * Type CollectionSurfaceDensity
 *
 * @description
 * The two row/head rhythms `CollectionSurface` renders: `'comfortable'`
 * (44px head, ≥44px rows) is the touch-friendly default; `'compact'` (36px
 * head) trades touch target size for more rows in the viewport.
 *
 * @access public
 * @since 1.0.0
 */
export type CollectionSurfaceDensity = 'comfortable' | 'compact';
